-- F3: vigilancia de radicados en la Rama Judicial y avisos por Telegram. Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/002-f3-vigilancia.sql
SET client_encoding = 'UTF8';

-- ------------------------------------------------------------------ vigilancia
-- Fuente SIMULADA: actuaciones escritas a mano para demostraciones y pruebas (los radicados de la base
-- de pruebas NO deben consultarse en el portal real: algunos coinciden con procesos reales de terceros).
ALTER TABLE vigilancia.radicados_vigilados DROP CONSTRAINT IF EXISTS radicados_vigilados_fuente_check;
ALTER TABLE vigilancia.radicados_vigilados ADD CONSTRAINT radicados_vigilados_fuente_check
    CHECK (fuente IN ('MANUAL', 'SIMULADA', 'PORTAL_HTTP', 'PORTAL_NAVEGADOR', 'TERCERO'));
ALTER TABLE vigilancia.radicados_vigilados ADD COLUMN IF NOT EXISTS despacho_portal varchar(150);
ALTER TABLE vigilancia.radicados_vigilados ADD COLUMN IF NOT EXISTS ultimo_error varchar(300);
-- La primera consulta exitosa con una fuente solo guarda el historial (línea base) sin avisar; se
-- reinicia al cambiar de fuente.
ALTER TABLE vigilancia.radicados_vigilados ADD COLUMN IF NOT EXISTS linea_base_hecha boolean NOT NULL DEFAULT false;

-- Actuaciones ya vistas de cada radicado: lo que no esté aquí es nuevo.
CREATE TABLE IF NOT EXISTS vigilancia.actuaciones_conocidas (
    radicado        char(23)     NOT NULL REFERENCES vigilancia.radicados_vigilados ON DELETE CASCADE,
    referencia      varchar(60)  NOT NULL,     -- id de la actuación en la fuente (p. ej. PORTAL:1721903412)
    fecha           date         NOT NULL,
    actuacion       varchar(200) NOT NULL,
    anotacion       varchar(1000),
    vista           timestamptz  NOT NULL DEFAULT now(),
    avisada         boolean      NOT NULL,     -- false = línea base de la primera consulta
    PRIMARY KEY (radicado, referencia)
);

-- Actuaciones de la fuente simulada (se agregan desde la pantalla de vigilancia).
CREATE TABLE IF NOT EXISTS vigilancia.actuaciones_simuladas (
    id          integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    radicado    char(23)     NOT NULL REFERENCES vigilancia.radicados_vigilados ON DELETE CASCADE,
    fecha       date         NOT NULL,
    actuacion   varchar(200) NOT NULL,
    anotacion   varchar(1000),
    creada      timestamptz  NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA vigilancia TO svc_vigilancia;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA vigilancia TO svc_vigilancia;

-- ------------------------------------------------------------------ procesos
-- Providencias detectadas por la vigilancia: la referencia evita registrarlas dos veces.
ALTER TABLE procesos.providencias ADD COLUMN IF NOT EXISTS referencia_externa varchar(60);
CREATE UNIQUE INDEX IF NOT EXISTS uk_providencia_referencia ON procesos.providencias (referencia_externa);
ALTER TABLE procesos.providencias ALTER COLUMN clase TYPE varchar(200);
ALTER TABLE procesos.providencias ALTER COLUMN decision TYPE varchar(1000);

-- ------------------------------------------------------------------ notificaciones
-- Códigos de un solo uso para vincular el Telegram de una persona (/start <código> al bot).
CREATE TABLE IF NOT EXISTS notificaciones.vinculos_telegram (
    codigo      varchar(20)  PRIMARY KEY,
    id_persona  bigint       NOT NULL,
    creado      timestamptz  NOT NULL DEFAULT now(),
    usado       timestamptz
);
ALTER TABLE notificaciones.notificaciones ALTER COLUMN mensaje TYPE varchar(1000);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA notificaciones TO svc_notificaciones;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA notificaciones TO svc_notificaciones;
