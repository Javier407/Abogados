-- F5: bloqueo por intentos fallidos y registro de ingresos. Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/003-f5-seguridad.sql
SET client_encoding = 'UTF8';

ALTER TABLE identidad.usuarios ADD COLUMN IF NOT EXISTS intentos_fallidos smallint    NOT NULL DEFAULT 0;
ALTER TABLE identidad.usuarios ADD COLUMN IF NOT EXISTS bloqueado_hasta   timestamptz;
ALTER TABLE identidad.usuarios ADD COLUMN IF NOT EXISTS ultimo_ingreso    timestamptz;
ALTER TABLE identidad.usuarios ADD COLUMN IF NOT EXISTS clave_cambiada    timestamptz;

-- Cada intento de ingreso (exitoso o no): sirve para auditar y detectar ataques de fuerza bruta.
CREATE TABLE IF NOT EXISTS identidad.ingresos (
    id_ingreso  bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    usuario     varchar(120) NOT NULL,      -- lo que se escribió (puede no existir)
    id_usuario  bigint,                     -- NULL si el usuario no existe
    fecha       timestamptz  NOT NULL DEFAULT now(),
    exitoso     boolean      NOT NULL,
    motivo      varchar(40),                -- CLAVE_INCORRECTA, BLOQUEADO, INACTIVO, NO_EXISTE
    ip          varchar(45)
);
CREATE INDEX IF NOT EXISTS ix_ingresos_fecha ON identidad.ingresos (fecha DESC);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA identidad TO svc_identidad;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA identidad TO svc_identidad;
