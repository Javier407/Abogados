-- F8: cuentas administradas desde la app, anulación de pagos, cuota litis, gastos procesales y reportes. Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/006-f8-administracion.sql
SET client_encoding = 'UTF8';

-- Cuenta nueva o contraseña restablecida por el administrador: la persona debe cambiarla al entrar.
ALTER TABLE identidad.usuarios ADD COLUMN IF NOT EXISTS debe_cambiar_clave boolean NOT NULL DEFAULT false;

-- Un pago no se borra: se anula con motivo y queda en el historial (no cuenta para el saldo).
ALTER TABLE gabinete.pagos ADD COLUMN IF NOT EXISTS anulado_en      timestamptz;
ALTER TABLE gabinete.pagos ADD COLUMN IF NOT EXISTS anulado_por     bigint;
ALTER TABLE gabinete.pagos ADD COLUMN IF NOT EXISTS motivo_anulacion varchar(200);
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_pagos_anulacion') THEN
        ALTER TABLE gabinete.pagos ADD CONSTRAINT ck_pagos_anulacion
            CHECK ((anulado_en IS NULL) = (motivo_anulacion IS NULL));
    END IF;
END $$;

-- Liquidación de la parte variable (cuota litis, porcentaje de la cuantía, mixto) cuando termina el proceso.
ALTER TABLE gabinete.honorarios_pactados ADD COLUMN IF NOT EXISTS valor_base        numeric(16,2) CHECK (valor_base >= 0);
ALTER TABLE gabinete.honorarios_pactados ADD COLUMN IF NOT EXISTS valor_liquidado   numeric(16,2) CHECK (valor_liquidado >= 0);
ALTER TABLE gabinete.honorarios_pactados ADD COLUMN IF NOT EXISTS fecha_liquidacion date;

-- Gastos del proceso (copias, notificaciones, honorarios del perito, pólizas...).
--   pagado_por FIRMA y reembolsable: la firma lo adelantó y el cliente debe devolverlo.
CREATE TABLE IF NOT EXISTS gabinete.gastos (
    id_gasto        integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso      integer       NOT NULL,                 -- procesos.procesos.id_proceso
    id_cliente      integer       NOT NULL REFERENCES gabinete.clientes,
    fecha           date          NOT NULL,
    concepto        varchar(150)  NOT NULL,
    valor           numeric(14,2) NOT NULL CHECK (valor > 0),
    pagado_por      varchar(8)    NOT NULL CHECK (pagado_por IN ('FIRMA', 'CLIENTE')),
    reembolsable    boolean       NOT NULL DEFAULT false,
    reembolsado_en  date,
    soporte_url     varchar(300),
    registrado_por  bigint,
    registrado      timestamptz   NOT NULL DEFAULT now(),
    CHECK (pagado_por = 'FIRMA' OR NOT reembolsable),
    CHECK (reembolsable OR reembolsado_en IS NULL)
);
CREATE INDEX IF NOT EXISTS ix_gastos_proceso ON gabinete.gastos (id_proceso);
CREATE INDEX IF NOT EXISTS ix_gastos_cliente ON gabinete.gastos (id_cliente);

-- Fecha en que se cumplió cada término (para medir si fue a tiempo). Los ya cumplidos antes de F8 quedan sin fecha.
ALTER TABLE procesos.terminos ADD COLUMN IF NOT EXISTS cumplido_en date;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA gabinete TO svc_gabinete;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA gabinete TO svc_gabinete;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA identidad TO svc_identidad;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA procesos TO svc_procesos;
