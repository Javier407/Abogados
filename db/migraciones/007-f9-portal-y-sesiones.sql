-- ------------------------------------------------------------------ procesos

-- Eventos por publicar. Se escriben en la misma transacción que el cambio que anuncian; un proceso aparte los
-- envía a RabbitMQ con confirmación y los marca. Si RabbitMQ está caído, esperan aquí (no se pierden).
CREATE TABLE IF NOT EXISTS procesos.outbox (
    id_evento   bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clave       varchar(40)  NOT NULL,             -- routing key, p. ej. termino.por_vencer
    cuerpo      jsonb        NOT NULL,
    creado      timestamptz  NOT NULL DEFAULT now(),
    enviado_en  timestamptz,
    intentos    integer      NOT NULL DEFAULT 0,
    ultimo_error varchar(300)
);
CREATE INDEX IF NOT EXISTS ix_outbox_pendientes ON procesos.outbox (id_evento) WHERE enviado_en IS NULL;

-- Resumen en lenguaje sencillo que el abogado revisa y publica en el portal del cliente.
CREATE TABLE IF NOT EXISTS procesos.resumenes_cliente (
    id_resumen     integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso     integer      NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    texto          varchar(4000) NOT NULL CHECK (length(btrim(texto)) >= 20),
    publicado_por  bigint       NOT NULL,
    publicado_en   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_resumenes_proceso ON procesos.resumenes_cliente (id_proceso, publicado_en DESC);

-- ------------------------------------------------------------------ vigilancia

CREATE TABLE IF NOT EXISTS vigilancia.outbox (
    id_evento   bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clave       varchar(40)  NOT NULL,
    cuerpo      jsonb        NOT NULL,
    creado      timestamptz  NOT NULL DEFAULT now(),
    enviado_en  timestamptz,
    intentos    integer      NOT NULL DEFAULT 0,
    ultimo_error varchar(300)
);
CREATE INDEX IF NOT EXISTS ix_outbox_pendientes ON vigilancia.outbox (id_evento) WHERE enviado_en IS NULL;

-- ------------------------------------------------------------------ notificaciones

-- Avisos al cliente: el abogado publicó un resumen en el portal.
ALTER TABLE notificaciones.notificaciones DROP CONSTRAINT IF EXISTS notificaciones_evento_check;
ALTER TABLE notificaciones.notificaciones ADD CONSTRAINT notificaciones_evento_check CHECK (evento IN
    ('actuacion.detectada', 'termino.por_vencer', 'termino.vencido', 'proceso.creado', 'audiencia.proxima',
     'portal.resumen_publicado'));

