-- F9: sesiones renovables y revocables, portal del cliente y entrega garantizada de eventos (outbox). Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/007-f9-portal-y-sesiones.sql
SET client_encoding = 'UTF8';

-- ------------------------------------------------------------------ identidad

-- La cuenta de un cliente se enlaza con su ficha en gabinete (valor, sin llave foránea entre esquemas).
-- El token lleva ese id y el portal solo muestra lo de ese cliente.
ALTER TABLE identidad.usuarios ADD COLUMN IF NOT EXISTS id_cliente integer CHECK (id_cliente > 0);
CREATE INDEX IF NOT EXISTS ix_usuarios_cliente ON identidad.usuarios (id_cliente) WHERE id_cliente IS NOT NULL;

-- Cada inicio de sesión abre una "familia" de refresh tokens. Cada renovación usa el token una sola vez y entrega
-- otro de la misma familia (rotación). Si un token ya usado vuelve a llegar, alguien lo copió: se revoca la familia.
-- Solo se guarda el SHA-256 del token, nunca el token.
CREATE TABLE IF NOT EXISTS identidad.sesiones (
    id_refresco    uuid         PRIMARY KEY,
    familia        uuid         NOT NULL,
    id_usuario     bigint       NOT NULL REFERENCES identidad.usuarios ON DELETE CASCADE,
    hash_refresco  char(64)     NOT NULL UNIQUE,
    emitido        timestamptz  NOT NULL DEFAULT now(),
    expira         timestamptz  NOT NULL,          -- de este refresh token
    familia_expira timestamptz  NOT NULL,          -- límite absoluto de la sesión
    usado_en       timestamptz,                    -- se renovó con él (ya no sirve)
    revocado_en    timestamptz,
    motivo         varchar(40),
    jti            uuid,                           -- token de acceso entregado junto con este refresh token
    jti_expira     timestamptz,
    ip             varchar(45),
    CHECK (expira <= familia_expira)
);
CREATE INDEX IF NOT EXISTS ix_sesiones_familia ON identidad.sesiones (familia);
CREATE INDEX IF NOT EXISTS ix_sesiones_usuario ON identidad.sesiones (id_usuario) WHERE revocado_en IS NULL;

-- Tokens de acceso cortados antes de vencer (cerrar sesión, cuenta desactivada, clave cambiada).
-- El gateway consulta esta lista; cada fila se borra cuando el token vence de todos modos.
CREATE TABLE IF NOT EXISTS identidad.tokens_revocados (
    jti    uuid        PRIMARY KEY,
    expira timestamptz NOT NULL
);

