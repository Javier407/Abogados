-- F10: expediente digital (documentos del proceso) y consulta inicial. Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/008-f10-documentos-y-consultas.sql
SET client_encoding = 'UTF8';

-- ------------------------------------------------------------------ procesos: documentos

-- El archivo se guarda en el volumen "documentos" con un nombre aleatorio (archivo); aquí van sus datos.
-- El nombre original solo se usa para descargarlo. sha256 permite comprobar que el archivo no cambió.
CREATE TABLE IF NOT EXISTS procesos.documentos (
    id_documento     integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso       integer       NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    archivo          uuid          NOT NULL UNIQUE,
    nombre           varchar(200)  NOT NULL,
    tipo_mime        varchar(100)  NOT NULL,
    tamano           bigint        NOT NULL CHECK (tamano > 0),
    sha256           char(64)      NOT NULL,
    categoria        varchar(15)   NOT NULL CHECK (categoria IN
                     ('PODER', 'DEMANDA', 'CONTESTACION', 'MEMORIAL', 'PRUEBA', 'PROVIDENCIA', 'CONTRATO', 'OTRO')),
    descripcion      varchar(300),
    visible_cliente  boolean       NOT NULL DEFAULT false,   -- el cliente lo ve en su portal
    subido_por       bigint        NOT NULL,
    subido           timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_documentos_proceso ON procesos.documentos (id_proceso, subido DESC);

-- ------------------------------------------------------------------ gabinete: consultas iniciales

-- Una persona que consulta antes de ser cliente. Si contrata, se crea (o enlaza) su ficha de cliente.
CREATE TABLE IF NOT EXISTS gabinete.consultas (
    id_consulta           integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    fecha                 date          NOT NULL DEFAULT CURRENT_DATE,
    nombre                varchar(150)  NOT NULL,
    tipo_documento        varchar(3)    CHECK (tipo_documento IN ('CC', 'CE', 'NIT', 'PAS')),
    numero_documento      varchar(15),
    email                 varchar(120),
    telefono              varchar(20),
    contraparte           varchar(150),
    contraparte_documento varchar(15),
    codigo_rama           varchar(20),
    asunto                varchar(300)  NOT NULL,
    descripcion           varchar(2000),
    id_abogado            bigint,                         -- quien atiende la consulta (gabinete.personal)
    estado                varchar(15)   NOT NULL DEFAULT 'ABIERTA'
                          CHECK (estado IN ('ABIERTA', 'CONTRATADA', 'NO_CONTRATADA', 'REMITIDA')),
    motivo_cierre         varchar(300),
    id_cliente            integer       REFERENCES gabinete.clientes,
    registrada_por        bigint,
    creada                timestamptz   NOT NULL DEFAULT now(),
    CHECK ((estado = 'CONTRATADA') = (id_cliente IS NOT NULL)),
    CHECK (estado IN ('ABIERTA', 'CONTRATADA') OR motivo_cierre IS NOT NULL),
    CHECK ((tipo_documento IS NULL) = (numero_documento IS NULL))
);
CREATE INDEX IF NOT EXISTS ix_consultas_estado ON gabinete.consultas (estado, fecha DESC);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA procesos TO svc_procesos;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA procesos TO svc_procesos;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA gabinete TO svc_gabinete;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA gabinete TO svc_gabinete;
