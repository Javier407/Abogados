-- F12: reglas de términos editables y validadas por un socio; historial de revisiones del vigía. Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/009-f12-reglas-y-servidor.sql
SET client_encoding = 'UTF8';

-- ------------------------------------------------------------------ procesos: reglas de términos

-- Una regla desactivada deja de sugerir términos (no se borra: los términos ya creados la citan por su descripción).
-- validada_por / validada_en: el socio que la revisó. Cualquier cambio de contenido la deja otra vez sin validar.
ALTER TABLE procesos.reglas_termino
    ADD COLUMN IF NOT EXISTS activa          boolean      NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS validada_por    bigint,
    ADD COLUMN IF NOT EXISTS validada_en     timestamptz,
    ADD COLUMN IF NOT EXISTS modificada_por  bigint,
    ADD COLUMN IF NOT EXISTS modificada_en   timestamptz;

-- Quién cambió qué y cuándo (también los días de contestación de un tipo de proceso, que usa la regla de contestar).
CREATE TABLE IF NOT EXISTS procesos.reglas_termino_historial (
    id_cambio   bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_regla    smallint      NOT NULL REFERENCES procesos.reglas_termino ON DELETE CASCADE,
    momento     timestamptz   NOT NULL DEFAULT now(),
    id_usuario  bigint        NOT NULL,
    accion      varchar(12)   NOT NULL CHECK (accion IN ('CREADA', 'EDITADA', 'VALIDADA', 'ACTIVADA', 'DESACTIVADA')),
    detalle     varchar(500)
);
CREATE INDEX IF NOT EXISTS reglas_termino_historial_regla ON procesos.reglas_termino_historial (id_regla, momento DESC);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA procesos TO svc_procesos;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA procesos TO svc_procesos;

-- ------------------------------------------------------------------ operacion: historial del vigía

-- Lo escribe infra/monitoreo/vigia.sh (cada 5 minutos, se guardan 90 días) y lo lee notificaciones para la
-- pantalla "Servidor" del administrador.
CREATE SCHEMA IF NOT EXISTS operacion;

CREATE TABLE IF NOT EXISTS operacion.revisiones (
    momento         timestamptz  PRIMARY KEY DEFAULT now(),
    disco           smallint     CHECK (disco BETWEEN 0 AND 100),     -- % de uso del disco raíz
    memoria_mb      integer      CHECK (memoria_mb >= 0),             -- memoria disponible
    respaldo_horas  integer,                                          -- edad del último respaldo (null = no hay)
    app_ok          boolean      NOT NULL,                            -- la app respondió por HTTPS
    problemas       smallint     NOT NULL DEFAULT 0,
    detalle         text                                              -- los problemas, uno por línea
);

-- Un incidente va desde que el vigía ve un problema hasta que deja de verlo (fin null = sigue abierto).
CREATE TABLE IF NOT EXISTS operacion.incidentes (
    id_incidente  bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    clave         varchar(80)   NOT NULL,
    mensaje       varchar(300)  NOT NULL,
    inicio        timestamptz   NOT NULL DEFAULT now(),
    fin           timestamptz,
    CHECK (fin IS NULL OR fin >= inicio)
);
CREATE INDEX IF NOT EXISTS incidentes_inicio ON operacion.incidentes (inicio DESC);
CREATE UNIQUE INDEX IF NOT EXISTS incidentes_abierto ON operacion.incidentes (clave) WHERE fin IS NULL;

GRANT USAGE ON SCHEMA operacion TO svc_notificaciones;
GRANT SELECT ON ALL TABLES IN SCHEMA operacion TO svc_notificaciones;
