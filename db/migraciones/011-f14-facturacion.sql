-- F14: facturación electrónica lista para la DIAN (con un proveedor SIMULADO hasta contratar uno real). Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/011-f14-facturacion.sql
SET client_encoding = 'UTF8';

-- Una sola fila. IVA y retención son de referencia hasta que el contador los valide (validada_por / validada_en).
-- La resolución de numeración la expide la DIAN; mientras se habilita, se usa el rango del set de pruebas
-- (prefijo SETP, 990000000 a 995000000) con ambiente PRUEBAS.
CREATE TABLE IF NOT EXISTS gabinete.facturacion_config (
    id_config           smallint      PRIMARY KEY DEFAULT 1 CHECK (id_config = 1),
    responsable_iva     boolean       NOT NULL DEFAULT true,
    tarifa_iva          numeric(5,2)  NOT NULL DEFAULT 19.00 CHECK (tarifa_iva BETWEEN 0 AND 100),
    retencion_juridica  numeric(5,2)  NOT NULL DEFAULT 11.00 CHECK (retencion_juridica BETWEEN 0 AND 100),
    retencion_natural   numeric(5,2)  NOT NULL DEFAULT 0 CHECK (retencion_natural BETWEEN 0 AND 100),
    dias_credito        smallint      NOT NULL DEFAULT 30 CHECK (dias_credito BETWEEN 0 AND 365),
    resolucion          varchar(30)   NOT NULL,
    prefijo             varchar(4)    NOT NULL,
    rango_desde         bigint        NOT NULL CHECK (rango_desde > 0),
    rango_hasta         bigint        NOT NULL,
    siguiente           bigint        NOT NULL,
    vigente_desde       date          NOT NULL,
    vigente_hasta       date          NOT NULL,
    prefijo_nota        varchar(4)    NOT NULL DEFAULT 'NC',
    siguiente_nota      bigint        NOT NULL DEFAULT 1 CHECK (siguiente_nota > 0),
    ambiente            varchar(10)   NOT NULL DEFAULT 'PRUEBAS' CHECK (ambiente IN ('PRUEBAS', 'PRODUCCION')),
    proveedor           varchar(20)   NOT NULL DEFAULT 'SIMULADO',
    validada_por        bigint,
    validada_en         timestamptz,
    CHECK (rango_hasta >= rango_desde),
    CHECK (siguiente BETWEEN rango_desde AND rango_hasta + 1),
    CHECK (vigente_hasta >= vigente_desde)
);
INSERT INTO gabinete.facturacion_config (id_config, resolucion, prefijo, rango_desde, rango_hasta, siguiente,
       vigente_desde, vigente_hasta)
VALUES (1, '18760000001', 'SETP', 990000000, 995000000, 990000000, DATE '2026-01-01', DATE '2027-12-31')
ON CONFLICT (id_config) DO NOTHING;

-- La factura guarda una copia de los datos del cliente y de la firma al emitirla: no cambia si después cambian.
CREATE TABLE IF NOT EXISTS gabinete.facturas (
    id_factura          integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    prefijo             varchar(4)    NOT NULL,
    numero              bigint        NOT NULL,
    resolucion          varchar(30)   NOT NULL,
    ambiente            varchar(10)   NOT NULL CHECK (ambiente IN ('PRUEBAS', 'PRODUCCION')),
    id_cliente          integer       NOT NULL REFERENCES gabinete.clientes,
    id_proceso          integer,                                  -- procesos.procesos.id_proceso (opcional)
    emitida             timestamptz   NOT NULL,
    vence               date          NOT NULL,
    forma_pago          varchar(7)    NOT NULL CHECK (forma_pago IN ('CONTADO', 'CREDITO')),
    subtotal            numeric(14,2) NOT NULL CHECK (subtotal >= 0),   -- servicios, sin IVA
    iva                 numeric(14,2) NOT NULL CHECK (iva >= 0),
    reembolsos          numeric(14,2) NOT NULL CHECK (reembolsos >= 0), -- gastos del cliente: sin IVA ni retención
    total               numeric(14,2) NOT NULL CHECK (total > 0),
    retencion_pct       numeric(5,2)  NOT NULL CHECK (retencion_pct BETWEEN 0 AND 100),
    retencion           numeric(14,2) NOT NULL CHECK (retencion >= 0),  -- la descuenta el cliente (informativa)
    neto                numeric(14,2) NOT NULL,
    observaciones       varchar(300),
    cufe                char(96),
    estado              varchar(10)   NOT NULL CHECK (estado IN ('ACEPTADA', 'RECHAZADA', 'ANULADA')),
    respuesta           varchar(300),
    emitida_por         bigint        NOT NULL,
    cliente_nombre      varchar(150)  NOT NULL,
    cliente_documento   varchar(20)   NOT NULL,                 -- "NIT 900456789"
    cliente_direccion   varchar(150)  NOT NULL,
    cliente_ciudad      varchar(60)   NOT NULL,
    cliente_email       varchar(120)  NOT NULL,
    UNIQUE (prefijo, numero),
    CHECK (total = subtotal + iva + reembolsos),
    CHECK (neto = total - retencion)
);
CREATE INDEX IF NOT EXISTS ix_facturas_cliente ON gabinete.facturas (id_cliente, emitida DESC);

CREATE TABLE IF NOT EXISTS gabinete.factura_lineas (
    id_factura      integer       NOT NULL REFERENCES gabinete.facturas ON DELETE CASCADE,
    linea           smallint      NOT NULL CHECK (linea > 0),
    tipo            varchar(10)   NOT NULL CHECK (tipo IN ('SERVICIO', 'REEMBOLSO')),
    descripcion     varchar(200)  NOT NULL,
    cantidad        numeric(10,2) NOT NULL CHECK (cantidad > 0),
    valor_unitario  numeric(14,2) NOT NULL CHECK (valor_unitario > 0),
    iva_pct         numeric(5,2)  NOT NULL CHECK (iva_pct BETWEEN 0 AND 100),
    valor           numeric(14,2) NOT NULL CHECK (valor > 0),         -- cantidad × valor unitario
    iva             numeric(14,2) NOT NULL CHECK (iva >= 0),
    id_honorario    integer       REFERENCES gabinete.honorarios_pactados,
    id_gasto        integer       REFERENCES gabinete.gastos,
    PRIMARY KEY (id_factura, linea),
    CHECK (tipo = 'SERVICIO' OR (iva_pct = 0 AND iva = 0))
);

-- Un gasto reembolsable se cobra en una sola factura (vuelve a quedar libre si esa factura se anula).
ALTER TABLE gabinete.gastos ADD COLUMN IF NOT EXISTS id_factura integer REFERENCES gabinete.facturas;

-- Una factura emitida no se borra ni se edita: se anula con una nota crédito por el total.
CREATE TABLE IF NOT EXISTS gabinete.notas_credito (
    id_nota      integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    prefijo      varchar(4)    NOT NULL,
    numero       bigint        NOT NULL,
    id_factura   integer       NOT NULL UNIQUE REFERENCES gabinete.facturas,
    motivo       varchar(200)  NOT NULL,
    valor        numeric(14,2) NOT NULL CHECK (valor > 0),
    emitida      timestamptz   NOT NULL,
    emitida_por  bigint        NOT NULL,
    cude         char(96),
    estado       varchar(10)   NOT NULL CHECK (estado IN ('ACEPTADA', 'RECHAZADA')),
    respuesta    varchar(300),
    UNIQUE (prefijo, numero)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA gabinete TO svc_gabinete;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA gabinete TO svc_gabinete;
