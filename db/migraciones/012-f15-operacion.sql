-- F15: errores de los servicios recogidos por el vigía y avisos de seguridad de la cuenta. Idempotente.
-- Base existente: docker compose exec -T postgres psql -U gabinete_admin -d gabinete < ../db/migraciones/012-f15-operacion.sql
SET client_encoding = 'UTF8';

-- Líneas de error de los registros de cada contenedor (ERROR, FATAL, Traceback…). Las escribe vigia.sh cada 5
-- minutos (hasta 30 por servicio y vuelta) y se guardan 30 días. Las ve el administrador en la pantalla Servidor.
CREATE TABLE IF NOT EXISTS operacion.errores (
    id_error  bigint        PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    momento   timestamptz   NOT NULL DEFAULT now(),
    servicio  varchar(40)   NOT NULL,
    linea     varchar(500)  NOT NULL
);
CREATE INDEX IF NOT EXISTS errores_momento ON operacion.errores (momento DESC);
GRANT SELECT ON ALL TABLES IN SCHEMA operacion TO svc_notificaciones;

-- Aviso a la persona cuando cambia algo de la seguridad de su cuenta (contraseña, verificación en dos pasos, bloqueo).
