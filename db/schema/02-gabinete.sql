-- Esquema del servicio gabinete: la firma, su personal, clientes, peritos, tarifas, honorarios y pagos.
-- Regla de microservicios: las referencias a otros servicios (id_usuario, id_proceso, codigo_rama)
-- se guardan como valores, sin llave foránea entre esquemas.
SET client_encoding = 'UTF8';

CREATE SCHEMA gabinete AUTHORIZATION svc_gabinete;

CREATE TABLE gabinete.firma (
    id_firma      smallint     PRIMARY KEY,
    nit           varchar(15)  NOT NULL UNIQUE,
    razon_social  varchar(150) NOT NULL,
    email         varchar(120),
    telefono      varchar(20)
);

CREATE TABLE gabinete.sedes (
    id_sede       smallint     PRIMARY KEY,
    id_firma      smallint     NOT NULL REFERENCES gabinete.firma,
    nombre        varchar(60)  NOT NULL,
    ciudad        varchar(60)  NOT NULL,
    direccion     varchar(150) NOT NULL,
    telefono      varchar(20),
    es_principal  boolean      NOT NULL DEFAULT false
);
-- Solo una sede principal por firma
CREATE UNIQUE INDEX uk_sede_principal ON gabinete.sedes (id_firma) WHERE es_principal;

CREATE TABLE gabinete.cargos (
    id_cargo    smallint    PRIMARY KEY,
    codigo      varchar(20) NOT NULL UNIQUE,
    nombre      varchar(60) NOT NULL,
    es_abogado  boolean     NOT NULL      -- exige tarjeta profesional
);

-- Personal de la firma (abogados y administrativos). id_persona = número de cédula.
CREATE TABLE gabinete.personal (
    id_persona           bigint       PRIMARY KEY CHECK (id_persona > 0),
    nombres              varchar(60)  NOT NULL,
    apellidos            varchar(60)  NOT NULL,
    email                varchar(120) NOT NULL UNIQUE,
    telefono             varchar(20),
    id_cargo             smallint     NOT NULL REFERENCES gabinete.cargos,
    id_sede              smallint     NOT NULL REFERENCES gabinete.sedes,
    tarjeta_profesional  varchar(10)  UNIQUE,
    tarifa_hora          numeric(12,2) CHECK (tarifa_hora >= 0),
    fecha_ingreso        date         NOT NULL,
    id_usuario           bigint,      -- cuenta en identidad.usuarios (opcional)
    activo               boolean      NOT NULL DEFAULT true
);

-- Áreas de práctica: una por rama, dirigidas por un socio.
CREATE TABLE gabinete.areas_practica (
    id_area             smallint    PRIMARY KEY,
    codigo_rama         varchar(20) NOT NULL UNIQUE,   -- procesos.ramas.codigo
    nombre              varchar(60) NOT NULL,
    id_director         bigint      NOT NULL REFERENCES gabinete.personal
);

ALTER TABLE gabinete.personal
    ADD COLUMN id_area smallint REFERENCES gabinete.areas_practica;

CREATE TABLE gabinete.clientes (
    id_cliente        integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    tipo_persona      varchar(8)   NOT NULL CHECK (tipo_persona IN ('NATURAL', 'JURIDICA')),
    tipo_documento    varchar(3)   NOT NULL CHECK (tipo_documento IN ('CC', 'CE', 'NIT', 'PAS')),
    numero_documento  varchar(15)  NOT NULL,
    nombre            varchar(150) NOT NULL,
    email             varchar(120),
    telefono          varchar(20),
    direccion         varchar(150),
    ciudad            varchar(60)  NOT NULL,
    id_sede           smallint     NOT NULL REFERENCES gabinete.sedes,
    creado            date         NOT NULL DEFAULT CURRENT_DATE,
    UNIQUE (tipo_documento, numero_documento),
    CHECK ((tipo_persona = 'JURIDICA') = (tipo_documento = 'NIT'))
);

CREATE TABLE gabinete.peritos (
    id_perito        integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre           varchar(120) NOT NULL,
    especialidad     varchar(80)  NOT NULL,
    profesion        varchar(80)  NOT NULL,
    registro         varchar(30),             -- matrícula o registro profesional
    telefono         varchar(20),
    email            varchar(120),
    ciudad           varchar(60)  NOT NULL,
    tarifa_dictamen  numeric(14,2),
    calificacion     smallint     CHECK (calificacion BETWEEN 1 AND 5)
);

-- Salario mínimo por año: las tarifas en SMMLV se convierten a pesos con este valor.
CREATE TABLE gabinete.smmlv (
    anio   smallint      PRIMARY KEY,
    valor  numeric(12,2) NOT NULL CHECK (valor > 0)
);

-- Tarifas de referencia (Conalbos) y propias de la firma.
CREATE TABLE gabinete.tarifas (
    id_tarifa        smallint     PRIMARY KEY,
    fuente           varchar(10)  NOT NULL CHECK (fuente IN ('CONALBOS', 'FIRMA')),
    codigo_rama      varchar(20),               -- NULL = aplica a cualquier rama
    servicio         varchar(100) NOT NULL,
    tipo_servicio    varchar(15)  NOT NULL DEFAULT 'CUALQUIERA'
                     CHECK (tipo_servicio IN ('PRESENCIAL', 'VIRTUAL', 'REPRESENTACION', 'CUALQUIERA')),
    forma_cobro      varchar(20)  NOT NULL
                     CHECK (forma_cobro IN ('FIJO', 'MENSUAL', 'CUOTA_LITIS', 'MIXTO', 'PORCENTAJE_CUANTIA')),
    valor_smmlv      numeric(6,2),              -- valor fijo (o mínimo) en salarios mínimos
    valor_smmlv_max  numeric(6,2),              -- tope del rango, si aplica
    porcentaje       numeric(5,2) CHECK (porcentaje BETWEEN 0 AND 100),
    nota             varchar(200),
    vigente_desde    date         NOT NULL,
    vigente_hasta    date,
    CHECK (valor_smmlv IS NOT NULL OR porcentaje IS NOT NULL),
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

-- Honorarios acordados con el cliente para un proceso.
CREATE TABLE gabinete.honorarios_pactados (
    id_honorario    integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso      integer       NOT NULL UNIQUE,   -- procesos.procesos.id_proceso
    id_cliente      integer       NOT NULL REFERENCES gabinete.clientes,
    id_tarifa       smallint      REFERENCES gabinete.tarifas,   -- tarifa en que se basó (opcional)
    forma_cobro     varchar(20)   NOT NULL
                    CHECK (forma_cobro IN ('FIJO', 'MENSUAL', 'CUOTA_LITIS', 'MIXTO', 'PORCENTAJE_CUANTIA')),
    valor_fijo      numeric(14,2) CHECK (valor_fijo >= 0),
    porcentaje      numeric(5,2)  CHECK (porcentaje BETWEEN 0 AND 100),
    valor_estimado  numeric(16,2),
    fecha_pacto     date          NOT NULL,
    estado          varchar(10)   NOT NULL DEFAULT 'VIGENTE' CHECK (estado IN ('VIGENTE', 'CUMPLIDO', 'CANCELADO')),
    CHECK (valor_fijo IS NOT NULL OR porcentaje IS NOT NULL)
);

CREATE TABLE gabinete.pagos (
    id_pago       integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_honorario  integer       NOT NULL REFERENCES gabinete.honorarios_pactados ON DELETE CASCADE,
    fecha         date          NOT NULL,
    valor         numeric(14,2) NOT NULL CHECK (valor > 0),
    medio         varchar(15)   NOT NULL CHECK (medio IN ('TRANSFERENCIA', 'EFECTIVO', 'TARJETA', 'CONSIGNACION')),
    referencia    varchar(40)
);

GRANT USAGE ON SCHEMA gabinete TO svc_gabinete;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA gabinete TO svc_gabinete;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA gabinete TO svc_gabinete;
