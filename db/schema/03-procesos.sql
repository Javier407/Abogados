-- Esquema del servicio procesos: catálogos (ramas, tipos, despachos, festivos) y el expediente
-- (procesos, partes, asignaciones, actuaciones, providencias, pruebas y términos).
SET client_encoding = 'UTF8';

CREATE SCHEMA procesos AUTHORIZATION svc_procesos;

-- ============================ Catálogos ============================

CREATE TABLE procesos.ramas (
    codigo  varchar(20)  PRIMARY KEY,
    nombre  varchar(60)  NOT NULL,
    norma   varchar(120) NOT NULL
);

CREATE TABLE procesos.tipos_proceso (
    id_tipo                    smallint     PRIMARY KEY,
    codigo_rama                varchar(20)  NOT NULL REFERENCES procesos.ramas,
    nombre                     varchar(80)  NOT NULL,
    -- Término de referencia para contestar, en días hábiles (a validar). NULL = no aplica.
    termino_contestacion_dias  smallint     CHECK (termino_contestacion_dias > 0),
    UNIQUE (codigo_rama, nombre)
);

-- Los cuatro códigos forman los primeros 12 dígitos del radicado.
-- Los códigos de entidad y especialidad de este catálogo son DE EJEMPLO (validar con las tablas del CSJ).
CREATE TABLE procesos.despachos (
    id_despacho       smallint     PRIMARY KEY,
    nombre            varchar(150) NOT NULL,
    ciudad            varchar(60)  NOT NULL,
    cod_dane          char(5)      NOT NULL CHECK (cod_dane ~ '^[0-9]{5}$'),
    cod_entidad       char(2)      NOT NULL CHECK (cod_entidad ~ '^[0-9]{2}$'),
    cod_especialidad  char(2)      NOT NULL CHECK (cod_especialidad ~ '^[0-9]{2}$'),
    cod_despacho      char(3)      NOT NULL CHECK (cod_despacho ~ '^[0-9]{3}$'),
    codigo_rama       varchar(20)  REFERENCES procesos.ramas,
    email             varchar(120),
    UNIQUE (cod_dane, cod_entidad, cod_especialidad, cod_despacho)
);

-- Días en que no corren términos: festivos, vacancia judicial y Semana Santa.
CREATE TABLE procesos.festivos (
    fecha        date        PRIMARY KEY,
    descripcion  varchar(80) NOT NULL,
    tipo         varchar(15) NOT NULL CHECK (tipo IN ('FESTIVO', 'VACANCIA', 'SEMANA_SANTA'))
);

-- ============================ Expediente ============================

CREATE TABLE procesos.procesos (
    id_proceso           integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    radicado             char(23)     NOT NULL UNIQUE CHECK (radicado ~ '^[0-9]{23}$'),
    -- Desglose del radicado (columnas calculadas):
    cod_dane             char(5)      GENERATED ALWAYS AS (substr(radicado, 1, 5))   STORED,
    cod_entidad          char(2)      GENERATED ALWAYS AS (substr(radicado, 6, 2))   STORED,
    cod_especialidad     char(2)      GENERATED ALWAYS AS (substr(radicado, 8, 2))   STORED,
    cod_despacho         char(3)      GENERATED ALWAYS AS (substr(radicado, 10, 3))  STORED,
    anio                 smallint     GENERATED ALWAYS AS (substr(radicado, 13, 4)::smallint) STORED,
    consecutivo          integer      GENERATED ALWAYS AS (substr(radicado, 17, 5)::integer)  STORED,
    instancia            smallint     GENERATED ALWAYS AS (substr(radicado, 22, 2)::smallint) STORED,
    id_tipo              smallint     NOT NULL REFERENCES procesos.tipos_proceso,
    -- Despacho que conoce ahora el proceso (p. ej. el tribunal en segunda instancia). NULL = el de origen.
    id_despacho_actual   smallint     REFERENCES procesos.despachos,
    id_cliente           integer      NOT NULL,    -- gabinete.clientes.id_cliente
    rol_cliente          varchar(20)  NOT NULL CHECK (rol_cliente IN
                         ('DEMANDANTE', 'DEMANDADO', 'VICTIMA', 'PROCESADO', 'ACCIONANTE', 'ACCIONADO')),
    asunto               varchar(200) NOT NULL,
    cuantia              numeric(16,2) CHECK (cuantia >= 0),
    clase_cuantia        varchar(12)  NOT NULL CHECK (clase_cuantia IN ('MINIMA', 'MENOR', 'MAYOR', 'SIN_CUANTIA')),
    tipo_servicio        varchar(15)  NOT NULL CHECK (tipo_servicio IN ('PRESENCIAL', 'VIRTUAL', 'REPRESENTACION')),
    estado               varchar(12)  NOT NULL DEFAULT 'ACTIVO'
                         CHECK (estado IN ('ACTIVO', 'SUSPENDIDO', 'TERMINADO', 'ARCHIVADO')),
    etapa                varchar(15)  NOT NULL CHECK (etapa IN
                         ('PODER', 'DEMANDA', 'ADMISION', 'NOTIFICACION', 'CONTESTACION', 'INVESTIGACION',
                          'PRUEBAS', 'AUDIENCIA', 'JUICIO', 'SENTENCIA', 'RECURSO', 'CERRADO')),
    fecha_radicacion     date         NOT NULL,
    vigilado             boolean      NOT NULL DEFAULT true,   -- lo consulta el servicio vigilancia
    creado               timestamptz  NOT NULL DEFAULT now(),
    CHECK (instancia >= 0 AND anio BETWEEN 1990 AND 2100),
    CHECK (estado NOT IN ('TERMINADO', 'ARCHIVADO') OR etapa = 'CERRADO'),
    -- El despacho de origen sale del propio radicado: si los 12 primeros dígitos no
    -- corresponden a un despacho registrado, el proceso no se puede guardar.
    FOREIGN KEY (cod_dane, cod_entidad, cod_especialidad, cod_despacho)
        REFERENCES procesos.despachos (cod_dane, cod_entidad, cod_especialidad, cod_despacho)
);
CREATE INDEX ix_procesos_cliente ON procesos.procesos (id_cliente);
CREATE INDEX ix_procesos_estado  ON procesos.procesos (estado);

CREATE TABLE procesos.partes (
    id_parte          integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso        integer      NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    rol               varchar(20)  NOT NULL CHECK (rol IN
                      ('DEMANDANTE', 'DEMANDADO', 'VICTIMA', 'PROCESADO', 'ACCIONANTE', 'ACCIONADO',
                       'TERCERO', 'LLAMADO_GARANTIA')),
    tipo_documento    varchar(3)   CHECK (tipo_documento IN ('CC', 'CE', 'NIT', 'PAS')),
    numero_documento  varchar(15),
    nombre            varchar(150) NOT NULL,
    es_cliente        boolean      NOT NULL DEFAULT false,
    apoderado         varchar(120)            -- abogado de la contraparte, si se conoce
);
CREATE INDEX ix_partes_proceso ON procesos.partes (id_proceso);

-- Quién lleva el proceso dentro de la firma.
CREATE TABLE procesos.asignaciones (
    id_proceso  integer     NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    id_persona  bigint      NOT NULL,          -- gabinete.personal.id_persona
    rol         varchar(12) NOT NULL CHECK (rol IN ('RESPONSABLE', 'APOYO', 'DEPENDIENTE')),
    desde       date        NOT NULL,
    PRIMARY KEY (id_proceso, id_persona)
);
-- Un solo abogado responsable por proceso.
CREATE UNIQUE INDEX uk_un_responsable ON procesos.asignaciones (id_proceso) WHERE rol = 'RESPONSABLE';

CREATE TABLE procesos.actuaciones (
    id_actuacion  integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso    integer      NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    fecha         date         NOT NULL,       -- si es futura, la actuación está programada
    tipo          varchar(15)  NOT NULL CHECK (tipo IN
                  ('PODER', 'DEMANDA', 'CONTESTACION', 'MEMORIAL', 'RECURSO', 'AUDIENCIA',
                   'ALEGATOS', 'NOTIFICACION', 'OTRO')),
    descripcion   varchar(200) NOT NULL,
    id_persona    bigint,                      -- quién la hizo o la tiene a cargo
    documento_url varchar(300)
);
CREATE INDEX ix_actuaciones_proceso ON procesos.actuaciones (id_proceso, fecha);

-- Decisiones del juez. Los autos se notifican por estado electrónico (fecha_estado).
CREATE TABLE procesos.providencias (
    id_providencia     integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso         integer      NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    tipo               varchar(10)  NOT NULL CHECK (tipo IN ('AUTO', 'SENTENCIA')),
    clase              varchar(120) NOT NULL,     -- p. ej. 'Admite demanda', 'Decreta pruebas'
    fecha_providencia  date         NOT NULL,
    fecha_estado       date         NOT NULL,     -- fecha de notificación por estado
    decision           varchar(300),
    sentido            varchar(15)  CHECK (sentido IN ('FAVORABLE', 'DESFAVORABLE', 'PARCIAL')),
    fuente             varchar(10)  NOT NULL DEFAULT 'MANUAL' CHECK (fuente IN ('MANUAL', 'VIGILANCIA')),
    CHECK (fecha_estado >= fecha_providencia),
    CHECK (tipo = 'SENTENCIA' OR sentido IS NULL)
);
CREATE INDEX ix_providencias_proceso ON procesos.providencias (id_proceso, fecha_estado);

CREATE TABLE procesos.pruebas (
    id_prueba    integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso   integer      NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    tipo         varchar(15)  NOT NULL CHECK (tipo IN
                 ('DOCUMENTAL', 'PERICIAL', 'TESTIMONIAL', 'INTERROGATORIO', 'INSPECCION', 'VIDEO', 'ANEXO')),
    descripcion  varchar(200) NOT NULL,
    id_perito    integer,                    -- gabinete.peritos.id_perito (solo si es pericial)
    estado       varchar(12)  NOT NULL CHECK (estado IN ('SOLICITADA', 'DECRETADA', 'PRACTICADA', 'NEGADA')),
    CHECK (tipo = 'PERICIAL' OR id_perito IS NULL)
);

CREATE TABLE procesos.terminos (
    id_termino         integer      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_proceso         integer      NOT NULL REFERENCES procesos.procesos ON DELETE CASCADE,
    id_providencia     integer      REFERENCES procesos.providencias,   -- la que originó el término
    descripcion        varchar(150) NOT NULL,
    fecha_inicio       date         NOT NULL,    -- notificación; el conteo empieza el día hábil siguiente
    dias_habiles       smallint     NOT NULL CHECK (dias_habiles > 0),
    fecha_vencimiento  date         NOT NULL,
    estado             varchar(10)  NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'CUMPLIDO')),
    id_responsable     bigint       NOT NULL,    -- gabinete.personal.id_persona
    CHECK (fecha_vencimiento > fecha_inicio)
);
CREATE INDEX ix_terminos_pendientes ON procesos.terminos (fecha_vencimiento) WHERE estado = 'PENDIENTE';

-- ============================ Funciones y vistas ============================

-- ¿Es día hábil judicial? (lunes a viernes y no festivo/vacancia)
CREATE FUNCTION procesos.es_dia_habil(d date) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT extract(isodow FROM d) < 6
       AND NOT EXISTS (SELECT 1 FROM procesos.festivos f WHERE f.fecha = d);
$$;

-- Fecha que resulta de contar n días hábiles a partir del día siguiente a 'desde'.
CREATE FUNCTION procesos.sumar_dias_habiles(desde date, n integer) RETURNS date
LANGUAGE plpgsql STABLE AS $$
DECLARE
    d       date := desde;
    contados integer := 0;
BEGIN
    WHILE contados < n LOOP
        d := d + 1;
        IF procesos.es_dia_habil(d) THEN
            contados := contados + 1;
        END IF;
    END LOOP;
    RETURN d;
END;
$$;

-- Días hábiles en el intervalo (desde, hasta].
CREATE FUNCTION procesos.dias_habiles_entre(desde date, hasta date) RETURNS integer
LANGUAGE sql STABLE AS $$
    SELECT count(*)::integer
    FROM generate_series(desde + 1, hasta, interval '1 day') AS g(d)
    WHERE procesos.es_dia_habil(g.d::date);
$$;

-- Términos con su situación respecto a hoy: lo que consulta el servicio para generar alertas.
CREATE VIEW procesos.v_terminos AS
SELECT t.*,
       CASE WHEN t.fecha_vencimiento >= CURRENT_DATE
            THEN  procesos.dias_habiles_entre(CURRENT_DATE, t.fecha_vencimiento)
            ELSE -procesos.dias_habiles_entre(t.fecha_vencimiento, CURRENT_DATE)
       END AS dias_habiles_restantes,
       CASE WHEN t.estado = 'CUMPLIDO'                     THEN 'CUMPLIDO'
            WHEN t.fecha_vencimiento < CURRENT_DATE        THEN 'VENCIDO'
            WHEN procesos.dias_habiles_entre(CURRENT_DATE, t.fecha_vencimiento) <= 5 THEN 'POR_VENCER'
            ELSE 'AL_DIA'
       END AS situacion
FROM procesos.terminos t;

-- Proceso con su rama, tipo y despachos de origen y actual.
CREATE VIEW procesos.v_procesos AS
SELECT p.id_proceso,
       p.radicado,
       p.cod_dane || '-' || p.cod_entidad || '-' || p.cod_especialidad || '-' || p.cod_despacho || '-' ||
       p.anio || '-' || lpad(p.consecutivo::text, 5, '0') || '-' || lpad(p.instancia::text, 2, '0') AS radicado_legible,
       r.codigo  AS codigo_rama,
       r.nombre  AS rama,
       t.nombre  AS tipo_proceso,
       dor.nombre AS despacho_origen,
       coalesce(dac.nombre, dor.nombre) AS despacho_actual,
       p.instancia,
       p.id_cliente, p.rol_cliente, p.asunto, p.cuantia, p.clase_cuantia, p.tipo_servicio,
       p.estado, p.etapa, p.fecha_radicacion, p.vigilado
FROM procesos.procesos p
JOIN procesos.tipos_proceso t ON t.id_tipo = p.id_tipo
JOIN procesos.ramas r          ON r.codigo = t.codigo_rama
JOIN procesos.despachos dor    ON (dor.cod_dane, dor.cod_entidad, dor.cod_especialidad, dor.cod_despacho)
                                = (p.cod_dane, p.cod_entidad, p.cod_especialidad, p.cod_despacho)
LEFT JOIN procesos.despachos dac ON dac.id_despacho = p.id_despacho_actual;

