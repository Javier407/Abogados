-- Esquema del servicio vigilancia: qué radicados se consultan en la Rama Judicial y el resultado de cada consulta.
SET client_encoding = 'UTF8';

CREATE SCHEMA vigilancia AUTHORIZATION svc_vigilancia;

CREATE TABLE vigilancia.radicados_vigilados (
    radicado             char(23)    PRIMARY KEY CHECK (radicado ~ '^[0-9]{23}$'),
    id_proceso           integer     NOT NULL,          -- procesos.procesos.id_proceso
    fuente               varchar(20) NOT NULL DEFAULT 'MANUAL'
                         CHECK (fuente IN ('MANUAL', 'PORTAL_HTTP', 'PORTAL_NAVEGADOR', 'TERCERO')),
    frecuencia_horas     smallint    NOT NULL DEFAULT 24 CHECK (frecuencia_horas >= 1),
    ultima_consulta      timestamptz,
    ultima_actuacion     date,                          -- fecha de la última actuación conocida
    fallos_consecutivos  smallint    NOT NULL DEFAULT 0,
    activo               boolean     NOT NULL DEFAULT true
);

CREATE TABLE vigilancia.consultas (
    id_consulta          bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    radicado             char(23)    NOT NULL REFERENCES vigilancia.radicados_vigilados ON DELETE CASCADE,
    fecha                timestamptz NOT NULL DEFAULT now(),
    exitosa              boolean     NOT NULL,
    actuaciones_nuevas   smallint    NOT NULL DEFAULT 0,
    detalle              jsonb                          -- respuesta resumida o error
);
CREATE INDEX ix_consultas_radicado ON vigilancia.consultas (radicado, fecha DESC);

GRANT USAGE ON SCHEMA vigilancia TO svc_vigilancia;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA vigilancia TO svc_vigilancia;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA vigilancia TO svc_vigilancia;
