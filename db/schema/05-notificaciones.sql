-- Esquema del servicio notificaciones: por dónde quiere recibir avisos cada persona y el historial de avisos.
SET client_encoding = 'UTF8';

CREATE SCHEMA notificaciones AUTHORIZATION svc_notificaciones;

CREATE TABLE notificaciones.preferencias (
    id_persona  bigint       NOT NULL,           -- gabinete.personal.id_persona
    canal       varchar(10)  NOT NULL CHECK (canal IN ('EMAIL', 'TELEGRAM', 'APP')),
    destino     varchar(120),                    -- correo o chat_id de Telegram; NULL para APP
    activo      boolean      NOT NULL DEFAULT true,
    PRIMARY KEY (id_persona, canal),
    CHECK (canal = 'APP' OR destino IS NOT NULL)
);

CREATE TABLE notificaciones.notificaciones (
    id_notificacion  bigint       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    id_persona       bigint       NOT NULL,
    canal            varchar(10)  NOT NULL CHECK (canal IN ('EMAIL', 'TELEGRAM', 'APP')),
    evento           varchar(30)  NOT NULL CHECK (evento IN
                     ('actuacion.detectada', 'termino.por_vencer', 'termino.vencido', 'proceso.creado')),
    titulo           varchar(120) NOT NULL,
    mensaje          varchar(500) NOT NULL,
    referencia       jsonb,                      -- p. ej. {"id_proceso": 3, "id_termino": 7}
    estado           varchar(10)  NOT NULL DEFAULT 'PENDIENTE'
                     CHECK (estado IN ('PENDIENTE', 'ENVIADA', 'FALLIDA', 'LEIDA')),
    creada           timestamptz  NOT NULL DEFAULT now(),
    enviada          timestamptz
);
CREATE INDEX ix_notif_persona ON notificaciones.notificaciones (id_persona, estado);

GRANT USAGE ON SCHEMA notificaciones TO svc_notificaciones;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA notificaciones TO svc_notificaciones;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA notificaciones TO svc_notificaciones;
