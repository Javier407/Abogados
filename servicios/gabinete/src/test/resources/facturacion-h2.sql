-- Esquema mínimo de facturación (F14) para probar FacturacionRepositorioJdbc sobre H2 en modo PostgreSQL.
CREATE SCHEMA IF NOT EXISTS gabinete;
DROP TABLE IF EXISTS gabinete.notas_credito;
DROP TABLE IF EXISTS gabinete.factura_lineas;
DROP TABLE IF EXISTS gabinete.gastos;
DROP TABLE IF EXISTS gabinete.facturas;
DROP TABLE IF EXISTS gabinete.facturacion_config;
DROP TABLE IF EXISTS gabinete.sedes;
DROP TABLE IF EXISTS gabinete.firma;

CREATE TABLE gabinete.firma (id_firma smallint PRIMARY KEY, nit varchar(15), razon_social varchar(150), email varchar(120),
    telefono varchar(20));
CREATE TABLE gabinete.sedes (id_sede smallint PRIMARY KEY, id_firma smallint, nombre varchar(60), ciudad varchar(60),
    direccion varchar(150), telefono varchar(20), es_principal boolean);
CREATE TABLE gabinete.facturacion_config (
    id_config smallint PRIMARY KEY, responsable_iva boolean, tarifa_iva numeric(5,2), retencion_juridica numeric(5,2),
    retencion_natural numeric(5,2), dias_credito smallint, resolucion varchar(30), prefijo varchar(4), rango_desde bigint,
    rango_hasta bigint, siguiente bigint, vigente_desde date, vigente_hasta date, prefijo_nota varchar(4),
    siguiente_nota bigint, ambiente varchar(10), proveedor varchar(20), validada_por bigint, validada_en timestamp with time zone);
CREATE TABLE gabinete.facturas (
    id_factura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, prefijo varchar(4), numero bigint, resolucion varchar(30),
    ambiente varchar(10), id_cliente integer, id_proceso integer, emitida timestamp with time zone, vence date,
    forma_pago varchar(7), subtotal numeric(14,2), iva numeric(14,2), reembolsos numeric(14,2), total numeric(14,2),
    retencion_pct numeric(5,2), retencion numeric(14,2), neto numeric(14,2), observaciones varchar(300), cufe char(96),
    estado varchar(10), respuesta varchar(300), emitida_por bigint, cliente_nombre varchar(150), cliente_documento varchar(20),
    cliente_direccion varchar(150), cliente_ciudad varchar(60), cliente_email varchar(120));
CREATE TABLE gabinete.factura_lineas (
    id_factura integer, linea smallint, tipo varchar(10), descripcion varchar(200), cantidad numeric(10,2),
    valor_unitario numeric(14,2), iva_pct numeric(5,2), valor numeric(14,2), iva numeric(14,2), id_honorario integer,
    id_gasto integer, PRIMARY KEY (id_factura, linea));
CREATE TABLE gabinete.gastos (id_gasto integer PRIMARY KEY, id_cliente integer, id_factura integer);
CREATE TABLE gabinete.notas_credito (
    id_nota integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, prefijo varchar(4), numero bigint, id_factura integer,
    motivo varchar(200), valor numeric(14,2), emitida timestamp with time zone, emitida_por bigint, cude char(96),
    estado varchar(10), respuesta varchar(300));

